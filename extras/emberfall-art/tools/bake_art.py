"""Bake art/src images (listed in art/manifest.json) into emberfall.py as PICS.
Replaces everything between the BEGIN/END PICS markers. Usage: python3 tools/bake_art.py"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import img2term as I

BEGIN = "# --- BEGIN PICS (generated by tools/bake_art.py - do not edit) ---"
END = "# --- END PICS ---"
GLYPH = {"▀": "h", "▄": "l", "█": "f", " ": " "}


def pack(img):
    enc = lambda i: "." if i is None else I.CODE[i]
    rows = []
    for row in img["rows"]:
        g = "".join(GLYPH[ch] for ch, _, _ in row)
        f = "".join(enc(None if ch == " " else fg) for ch, fg, _ in row)
        b = "".join(enc(None if ch in (" ", "▀", "▄") and bg is None else bg) for ch, _, bg in row)
        rows.append((g.rstrip(), f[:len(g.rstrip())], b[:len(g.rstrip())]))
    return {"w": img["w"], "h": img["h"], "pal": [tuple(c) for c in img["pal"]], "fb": img["fb"], "rows": rows}


def _is_skin(c):
    r, g, b = c
    return r > g > b and r - b > 30 and 90 <= r <= 250 and g >= 0.45 * r


def _mode(pixels):
    count, total = {}, {}
    for c in pixels:
        k = (c[0] >> 5, c[1] >> 5, c[2] >> 5)
        count[k] = count.get(k, 0) + 1
        t = total.setdefault(k, [0, 0, 0])
        t[0] += c[0]; t[1] += c[1]; t[2] += c[2]
    if not count:
        return None
    k = max(count, key=count.get)
    return tuple(v // count[k] for v in total[k])


def _lift(c, lo=85):
    """Keep colours visible on the map: brighten very dark ones."""
    if c is None:
        return None
    l = 0.3 * c[0] + 0.59 * c[1] + 0.11 * c[2]
    if l >= lo:
        return c
    k = lo / max(l, 1)
    return tuple(min(255, int(v * k)) for v in c)


def figure_tint(path):
    px = I.load_rgb(path, 96, 96)
    x0, y0, x1, y1 = I._bbox(px, 45, pad=0)
    pts = [(x, y, px[y][x]) for y in range(y0, y1) for x in range(x0, x1) if max(px[y][x]) >= 45]
    if not pts:
        return None
    hgt = max(1, y1 - y0)
    skin = _mode([c for x, y, c in pts if y < y0 + hgt * 0.7 and _is_skin(c)])
    hair = _mode([c for x, y, c in pts if y < y0 + hgt * 0.25 and not _is_skin(c)]) or skin
    cloth = _mode([c for x, y, c in pts if y > y0 + hgt * 0.68 and not _is_skin(c)])
    if not cloth:
        return None
    return {"h": _lift(hair, 70), "s": skin or (228, 186, 146), "#": _lift(cloth)}


def main():
    man = json.load(open(os.path.join(ROOT, "art", "manifest.json")))
    tints = {}
    for key, spec in man.items():
        if key.startswith("_") or spec.get("w", 34) > 40:
            continue  # scenes and title pictures are not figures
        t = figure_tint(os.path.join(ROOT, "art", "src", spec["src"]))
        if t:
            tints[key] = t
    out = [BEGIN, "FIG_TINT = {"]
    for key in sorted(tints):
        out.append("    %r: %r," % (key, tints[key]))
    out += ["}", "PICS = {"]
    for key, spec in man.items():
        if key.startswith("_"):
            continue
        img = I.convert(os.path.join(ROOT, "art", "src", spec["src"]), spec.get("w", 34), "half",
                        colors=spec.get("colors", 32), maxh=spec.get("maxh"), crop=spec.get("crop", True))
        p = pack(img)
        out.append("    %r: {\"w\": %d, \"h\": %d," % (key, p["w"], p["h"]))
        out.append("        \"pal\": %r," % (p["pal"],))
        out.append("        \"fb\": %r," % (p["fb"],))
        out.append("        \"rows\": [")
        for r in p["rows"]:
            out.append("            %r," % (r,))
        out.append("        ]},")
        print("%-12s %3dx%-3d %2d colours" % (key, p["w"], p["h"], len(p["pal"])))
    out += ["}", END]
    path = os.path.join(ROOT, "emberfall.py")
    if not os.path.exists(path):  # in the ASCII ARCADE repository: extras/emberfall-art -> ../../emberfall.py
        path = os.path.join(ROOT, "..", "..", "emberfall.py")
    src = open(path, encoding="utf-8").read()
    a, b = src.index(BEGIN), src.index(END) + len(END)
    open(path, "w", encoding="utf-8").write(src[:a] + "\n".join(out) + src[b:])


if __name__ == "__main__":
    main()
